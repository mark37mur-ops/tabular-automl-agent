_STAT = {"AVG": "среднее", "MODE": "мода", "MEDI": "медиана"}
_PERIOD = {"HOUR": "час", "DAY": "день", "WEEK": "неделю", "MON": "месяц", "QRT": "квартал", "YEAR": "год"}


def home_credit(name: str) -> tuple[str, str]:
    if name in HOME_CREDIT:
        return HOME_CREDIT[name]
    m = re.fullmatch(r"(\w+?)_(AVG|MODE|MEDI)", name)
    if m and m.group(1) in _BUILDING:
        return (f"Нормализованная характеристика дома, где живёт клиент: {_BUILDING[m.group(1)]} ({_STAT[m.group(2)]})", "")
    m = re.fullmatch(r"FLAG_DOCUMENT_(\d+)", name)
    if m:
        return (f"Предоставил ли клиент документ №{m.group(1)} (1 — да)", "")
    m = re.fullmatch(r"AMT_REQ_CREDIT_BUREAU_(\w+)", name)
    if m:
        return (f"Количество запросов в бюро кредитных историй о клиенте за {_PERIOD[m.group(1)]} до подачи заявки", "шт.")
    raise KeyError(f"Нет описания для признака {name}")
